import Foundation

public enum AUState: String, CaseIterable, Codable, Sendable, Identifiable {
    case act = "ACT", nsw = "NSW", nt = "NT", qld = "QLD", sa = "SA", tas = "TAS", vic = "VIC", wa = "WA"

    public var id: String { rawValue }
    public var name: String {
        switch self {
        case .act: "Australian Capital Territory"
        case .nsw: "New South Wales"
        case .nt: "Northern Territory"
        case .qld: "Queensland"
        case .sa: "South Australia"
        case .tas: "Tasmania"
        case .vic: "Victoria"
        case .wa: "Western Australia"
        }
    }
}

public struct PublicHoliday: Hashable, Sendable, Codable {
    public var date: CivilDate
    public var name: String
}

/// Bundled national and state public holidays (`Resources/au_public_holidays.json`, generated by
/// `scripts/generate_holidays.py`). Auto-detect is opt-in. The per-shift manual toggle always wins.
public struct PublicHolidayCalendar: Sendable {
    private let byState: [AUState: [CivilDate: String]]
    public let coveredYears: ClosedRange<Int>?

    struct File: Decodable {
        struct Entry: Decodable { let date: String; let name: String }
        let years: [Int]
        let states: [String: [Entry]]
    }

    public init(data: Data) throws {
        let file = try JSONDecoder().decode(File.self, from: data)
        var map: [AUState: [CivilDate: String]] = [:]
        for (key, entries) in file.states {
            guard let st = AUState(rawValue: key) else { continue }
            var dict: [CivilDate: String] = [:]
            for e in entries { if let d = CivilDate(e.date) { dict[d] = e.name } }
            map[st] = dict
        }
        byState = map
        if let lo = file.years.min(), let hi = file.years.max() { coveredYears = lo...hi } else { coveredYears = nil }
    }

    /// Loads the bundled list. Returns an empty calendar if the resource is missing.
    public static let bundled: PublicHolidayCalendar = {
        if let url = Bundle.module.url(forResource: "au_public_holidays", withExtension: "json"),
           let data = try? Data(contentsOf: url),
           let cal = try? PublicHolidayCalendar(data: data) {
            return cal
        }
        return PublicHolidayCalendar()
    }()

    init() { byState = [:]; coveredYears = nil }

    public func holiday(on date: CivilDate, state: AUState) -> PublicHoliday? {
        byState[state]?[date].map { PublicHoliday(date: date, name: $0) }
    }

    public func isHoliday(_ date: CivilDate, state: AUState) -> Bool { holiday(on: date, state: state) != nil }

    public func holidays(in range: DateRange, state: AUState) -> [PublicHoliday] {
        (byState[state] ?? [:]).filter { range.contains($0.key) }
            .map { PublicHoliday(date: $0.key, name: $0.value) }
            .sorted { $0.date < $1.date }
    }

    /// Suggested value for a shift's public-holiday flag. Detection uses the shift's start date,
    /// the same day the web app's manual flag applies to.
    public func suggestsPublicHoliday(for date: CivilDate, state: AUState, enabled: Bool) -> Bool {
        enabled && isHoliday(date, state: state)
    }
}
